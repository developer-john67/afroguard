function t(key, lang) {
    const language = lang || CURRENT_LANG.value;
    const dict = I18N[language] || I18N['en'];
    const keys = key.split('.');
    let result = dict;
    for (const k of keys) {
        if (result && typeof result === 'object' && k in result) {
            result = result[k];
        } else {
            return null;
        }
    }
    return typeof result === 'string' ? result : null;
}

